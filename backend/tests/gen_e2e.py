import os

lines = []
lines.append("import json, sys, time, unittest, urllib.request, urllib.error")
lines.append("BASE_URL = 'http://127.0.0.1:8000'")
lines.append("")
lines.append("def _post(path, body):")
lines.append("    data = json.dumps(body).encode()")
lines.append("    req = urllib.request.Request(BASE_URL+path, data=data, headers={'Content-Type':'application/json'}, method='POST')")
lines.append("    try:")
lines.append("        with urllib.request.urlopen(req) as r: return r.status, json.loads(r.read())")
lines.append("    except urllib.error.HTTPError as e: return e.code, json.loads(e.read())")
lines.append("")
lines.append("def _get(path):")
lines.append("    try:")
lines.append("        with urllib.request.urlopen(BASE_URL+path) as r: return r.status, json.loads(r.read())")
lines.append("    except urllib.error.HTTPError as e: return e.code, json.loads(e.read())")
lines.append("")
lines.append("VALID_DIRS = {'increases_failure_risk','decreases_failure_risk'}")
lines.append("VALID_RISK = {'LOW','MEDIUM','HIGH'}")
lines.append("")
lines.append("def _check(tc, body, lbl):")
lines.append("    for f in ('failure_probability','failure_predicted','is_anomaly','anomaly_score','risk_level','model_version','explanation','recommendations'):")
lines.append("        tc.assertIn(f, body, lbl+': missing '+f)")
lines.append("    tc.assertIsInstance(body['failure_probability'], float)")
lines.append("    tc.assertIsInstance(body['failure_predicted'], bool)")
lines.append("    tc.assertIsInstance(body['is_anomaly'], bool)")
lines.append("    tc.assertGreaterEqual(body['failure_probability'], 0.0)")
lines.append("    tc.assertLessEqual(body['failure_probability'], 1.0)")
lines.append("    tc.assertIn(body['risk_level'], VALID_RISK, lbl+': bad risk_level')")
lines.append("    exp = body['explanation']")
lines.append("    tc.assertIsNotNone(exp)")
lines.append("    tc.assertIn('top_factors', exp)")
lines.append("    for fac in exp['top_factors']:")
lines.append("        tc.assertIn(fac.get('direction'), VALID_DIRS)")
lines.append("    recs = body['recommendations']")
lines.append("    tc.assertIsNotNone(recs, lbl+': recs null')")
lines.append("    tc.assertEqual(recs['risk_level'], body['risk_level'], lbl+': risk_level mismatch')")
lines.append("    ids = [r['id'] for r in recs['recommendations']]")
lines.append("    tc.assertEqual(len(ids), len(set(ids)), lbl+': dup ids')")
lines.append("    for rec in recs['recommendations']:")
lines.append("        for field in ('id','category','severity','title','action'):")
lines.append("            tc.assertIn(field, rec)")
lines.append("")
lines.append("class E2E(unittest.TestCase):")
lines.append("")
lines.append("    def test_01_health(self):")
lines.append("        c,b = _get('/api/v1/health')")
lines.append("        self.assertEqual(c,200)")
lines.append("        self.assertEqual(b.get('status'),'ok')")
lines.append("        self.assertIn('version',b)")
lines.append("        print('  health:', b)")
lines.append("")
lines.append("    def test_02_baseline(self):")
lines.append("        p={\"type\":\"M\",\"air_temperature\":298.1,\"process_temperature\":308.6,\"rotational_speed\":1551,\"torque\":42.8,\"tool_wear\":120}")
lines.append("        c,b = _post('/api/v1/predict',p)")
lines.append("        self.assertEqual(c,200)")
lines.append("        _check(self,b,'baseline')")
lines.append("        print('  baseline fp=%s risk=%s anomaly=%s' % (b['failure_probability'],b['risk_level'],b['is_anomaly']))")
lines.append("")
lines.append("    def _ids(self, b): return [r['id'] for r in b['recommendations']['recommendations']]")
lines.append("    def _sev(self, b): return [r['severity'] for r in b['recommendations']['recommendations']]")
lines.append("    def _facs(self, b): return b['explanation']['top_factors']")
lines.append("    def _has_pos_shap(self, facs, keyword): return any(keyword in f['feature'].lower() and f['direction']=='increases_failure_risk' for f in facs)")
lines.append("")
lines.append("    def test_sc01_normal(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1500,'torque':40.0,'tool_wear':50})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc01')")
lines.append("        print('  sc01 fp=%s risk=%s anomaly=%s recs=%s'%(b['failure_probability'],b['risk_level'],b['is_anomaly'],self._ids(b)))")
lines.append("")
lines.append("    def test_sc02_anomaly_independence(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'L','air_temperature':299.0,'process_temperature':309.0,'rotational_speed':1600,'torque':38.0,'tool_wear':80})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc02')")
lines.append("        ids = self._ids(b)")
lines.append("        if b['is_anomaly'] and b['risk_level']=='LOW':")
lines.append("            self.assertIn('REC-ANOM-001',ids)")
lines.append("            self.assertNotIn('REC-ANOM-HIGH-001',ids)")
lines.append("        print('  sc02 anomaly=%s risk=%s recs=%s'%(b['is_anomaly'],b['risk_level'],ids))")
lines.append("")
lines.append("    def test_sc03_high_failure(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'L','air_temperature':305.0,'process_temperature':315.0,'rotational_speed':1200,'torque':70.0,'tool_wear':240})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc03')")
lines.append("        if b['risk_level']=='HIGH': self.assertIn('CRITICAL',self._sev(b))")
lines.append("        print('  sc03 fp=%s risk=%s recs=%s'%(b['failure_probability'],b['risk_level'],self._ids(b)))")
lines.append("")
lines.append("    def test_sc04_anomaly_high(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'L','air_temperature':306.0,'process_temperature':316.0,'rotational_speed':1100,'torque':72.0,'tool_wear':250})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc04')")
lines.append("        ids = self._ids(b)")
lines.append("        if b['is_anomaly'] and b['risk_level']=='HIGH':")
lines.append("            self.assertIn('REC-ANOM-HIGH-001',ids)")
lines.append("            self.assertNotIn('REC-ANOM-001',ids)")
lines.append("        print('  sc04 anomaly=%s risk=%s recs=%s'%(b['is_anomaly'],b['risk_level'],ids))")
lines.append("")
lines.append("    def test_sc05_tool_wear(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1400,'torque':60.0,'tool_wear':230})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc05')")
lines.append("        ids = self._ids(b); facs = self._facs(b)")
lines.append("        tp = self._has_pos_shap(facs,'tool')")
lines.append("        if tp:")
lines.append("            self.assertTrue(any('REC-TOOL' in i for i in ids),'pos tool shap but no TOOLING rec')")
lines.append("            if 'REC-TOOL-002' in ids: self.assertNotIn('REC-TOOL-001',ids)")
lines.append("        print('  sc05 fp=%s tool_pos=%s recs=%s'%(b['failure_probability'],tp,ids))")
lines.append("")
lines.append("    def test_sc06_torque(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'H','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':2800,'torque':70.0,'tool_wear':100})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc06')")
lines.append("        ids = self._ids(b); facs = self._facs(b)")
lines.append("        tp = self._has_pos_shap(facs,'torque')")
lines.append("        if tp: self.assertIn('REC-MECH-001',ids,'pos torque shap but no REC-MECH-001')")
lines.append("        print('  sc06 fp=%s torque_pos=%s recs=%s'%(b['failure_probability'],tp,ids))")
lines.append("")
lines.append("    def test_sc07_temperature(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':304.0,'process_temperature':315.0,'rotational_speed':1500,'torque':42.0,'tool_wear':100})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc07')")
lines.append("        ids = self._ids(b); facs = self._facs(b)")
lines.append("        tp = any(any(t in f['feature'].lower() for t in ('temp','temperature')) and f['direction']=='increases_failure_risk' for f in facs)")
lines.append("        if tp: self.assertIn('REC-THRM-001',ids,'pos temp shap but no REC-THRM-001')")
lines.append("        else: self.assertNotIn('REC-THRM-001',ids,'REC-THRM-001 fired without pos temp shap')")
lines.append("        print('  sc07 fp=%s temp_pos=%s recs=%s'%(b['failure_probability'],tp,ids))")
lines.append("")
lines.append("    def test_sc08_no_dup_ids(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'L','air_temperature':304.0,'process_temperature':315.0,'rotational_speed':1100,'torque':70.0,'tool_wear':230})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc08')")
lines.append("        ids = self._ids(b)")
lines.append("        self.assertEqual(len(ids),len(set(ids)),'dup ids: '+str(ids))")
lines.append("        print('  sc08 recs=%s'%ids)")
lines.append("")
lines.append("    def test_sc09_shap_dirs(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1500,'torque':40.0,'tool_wear':120})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc09')")
lines.append("        for f in self._facs(b): self.assertIn(f['direction'],VALID_DIRS)")
lines.append("        print('  sc09 %d factors, all directions valid'%len(self._facs(b)))")
lines.append("")
lines.append("    def test_sc10_fallback(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1500,'torque':40.0,'tool_wear':50})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc10')")
lines.append("        ids = self._ids(b)")
lines.append("        self.assertEqual(len(ids),len(set(ids)))")
lines.append("        print('  sc10 risk=%s recs=%s'%(b['risk_level'],ids))")
lines.append("")
lines.append("    def test_sc11_medium(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':300.0,'process_temperature':311.0,'rotational_speed':1400,'torque':55.0,'tool_wear':160})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc11')")
lines.append("        ids = self._ids(b)")
lines.append("        if b['risk_level']=='MEDIUM': self.assertGreater(len(ids),0)")
lines.append("        print('  sc11 fp=%s risk=%s recs=%s'%(b['failure_probability'],b['risk_level'],ids))")
lines.append("")
lines.append("    def test_sc12_high_fallback(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'L','air_temperature':305.0,'process_temperature':315.0,'rotational_speed':1200,'torque':70.0,'tool_wear':240})")
lines.append("        self.assertEqual(c,200); _check(self,b,'sc12')")
lines.append("        if b['risk_level']=='HIGH': self.assertIn('CRITICAL',self._sev(b))")
lines.append("        print('  sc12 fp=%s risk=%s recs=%s'%(b['failure_probability'],b['risk_level'],self._ids(b)))")
lines.append("")
lines.append("    def test_err01_missing_field(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'rotational_speed':1500,'torque':40.0,'tool_wear':120})")
lines.append("        self.assertEqual(c,422); print('  err01 HTTP',c)")
lines.append("")
lines.append("    def test_err02_bad_type(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'X','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1500,'torque':40.0,'tool_wear':120})")
lines.append("        self.assertEqual(c,422); print('  err02 HTTP',c)")
lines.append("")
lines.append("    def test_err03_neg_temp(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':-10.0,'process_temperature':308.0,'rotational_speed':1500,'torque':40.0,'tool_wear':120})")
lines.append("        self.assertEqual(c,422); print('  err03 HTTP',c)")
lines.append("")
lines.append("    def test_err04_neg_speed(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':-100,'torque':40.0,'tool_wear':120})")
lines.append("        self.assertEqual(c,422); print('  err04 HTTP',c)")
lines.append("")
lines.append("    def test_err05_neg_torque(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1500,'torque':-5.0,'tool_wear':120})")
lines.append("        self.assertEqual(c,422); print('  err05 HTTP',c)")
lines.append("")
lines.append("    def test_err06_neg_tool_wear(self):")
lines.append("        c,b = _post('/api/v1/predict',{'type':'M','air_temperature':298.0,'process_temperature':308.0,'rotational_speed':1500,'torque':40.0,'tool_wear':-10})")
lines.append("        self.assertEqual(c,422); print('  err06 HTTP',c)")
lines.append("")
lines.append("def _ready(r=5,d=2):")
lines.append("    for _ in range(r):")
lines.append("        try:")
lines.append("            with urllib.request.urlopen(BASE_URL+'/api/v1/health') as resp:")
lines.append("                if resp.status==200: return True")
lines.append("        except Exception: pass")
lines.append("        time.sleep(d)")
lines.append("    return False")
lines.append("")
lines.append("if __name__=='__main__':")
lines.append("    print('Checking', BASE_URL)")
lines.append("    if not _ready():")
lines.append("        print('ERROR: server not reachable. Run: python -m uvicorn app.main:app --port 8000')")
lines.append("        sys.exit(1)")
lines.append("    print('Server ready. Running E2E tests...')")
lines.append("    loader=unittest.TestLoader(); loader.sortTestMethodsUsing=None")
lines.append("    runner=unittest.TextTestRunner(verbosity=2)")
lines.append("    result=runner.run(loader.loadTestsFromTestCase(E2E))")
lines.append("    sys.exit(0 if result.wasSuccessful() else 1)")

with open(os.path.join("tests","test_e2e.py"), "w", encoding="utf-8") as fout:
    fout.write("\n".join(lines) + "\n")
print("OK")
